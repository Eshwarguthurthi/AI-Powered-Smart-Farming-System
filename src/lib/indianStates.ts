// LGD spells some names differently ("The Dadra And Nagar Haveli And Daman And Diu").
export const normalizeStateName = (name: string) =>
  name.toLowerCase().replace(/&/g, "and").replace(/^the\s+/, "").replace(/\s+/g, " ").trim();
